// build.rs — compiles the Briev machinery (bridge/counsel.bv) to a native
// static library and links it into this crate.
//
// The compiler is a build-time dependency, so this script resolves one in this
// order:
//
//   1. `COUNSEL_BRIEVC` / `BRIEVC`  — an explicit binary (dev loop, CI)
//   2. the pinned release cache    — extracted once, then reused offline
//   3. `brievc` on PATH            — a locally installed compiler
//   4. the pinned GitHub release   — downloaded, sha256-verified, extracted
//
// A missing compiler is a hard error with instructions. Linking nothing and
// failing at the user's first call would be the worse failure mode.
//
// The release ships `<prefix>/bin/brievc` + `<prefix>/share/briev/`, and the
// compiler resolves its resource tree relative to its own executable
// (`resource_root()` prefers `<exe>/../share/briev` before any environment
// variable), so preserving that layout is what makes `BRIEV_HOME` unnecessary
// here. The autogenerated bindings (src/bindings.rs) were produced by
// `brievc bindings bridge/counsel.bv rust` and are checked in.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Pinned compiler release. Bumping it means regenerating `src/bindings.rs`
/// and re-running the tests: the bindings and the compiler must agree.
const RELEASE_TAG: &str = "v0.1.0";
/// Release asset stem — the tarball contains `<stem>/bin` + `<stem>/share`.
const ASSET_STEM: &str = "brievc-linux-x86_64";
/// sha256 of that exact tarball; a mismatch aborts the build.
const ASSET_SHA256: &str = "2e5d7e55b60ac45c29fb82fba36046e2fcfd2bfc4b78d87917ef14a0ba9bbe13";

fn main() {
    // docs.rs builds offline and never links; the `extern "C"` block in
    // src/lib.rs needs no linker at doc time, so skip the native half instead
    // of failing the docs build.
    if env::var_os("DOCS_RS").is_some() {
        println!("cargo:warning=counsel: docs.rs build — skipping the native machinery");
        emit_rerun_hints(None);
        return;
    }

    let brievc = resolve_brievc();
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let bridge = manifest.join("bridge/counsel.bv");
    let lib_out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("briev");

    build_machinery(&brievc, &bridge, &lib_out);

    // Bake the resolved compiler into the crate so the static half finds the
    // same one at check time. A crates.io consumer usually has no `brievc` on
    // PATH, and its own manifest directory is inside the registry cache — so
    // without this the checker reports NoCompiler even though the build just
    // fetched a perfectly good compiler.
    println!("cargo:rustc-env=COUNSEL_BRIEVC_PATH={}", brievc.display());
    println!(
        "cargo:rustc-env=COUNSEL_BRIEVC_CACHE_BIN={}",
        install_dir().join("bin").join("brievc").display()
    );

    // Link the produced static library; rebuild when the machinery changes.
    println!("cargo:rustc-link-search=native={}", lib_out.display());
    println!("cargo:rustc-link-lib=counsel");
    emit_rerun_hints(Some(&bridge));
}

/// Emit the `rerun-if-*` lines so a changed compiler or bridge rebuilds.
fn emit_rerun_hints(bridge: Option<&Path>) {
    if let Some(bridge) = bridge {
        println!("cargo:rerun-if-changed={}", bridge.display());
    }
    for var in [
        "BRIEVC",
        "COUNSEL_BRIEVC",
        "COUNSEL_CACHE_DIR",
        "COUNSEL_NO_DOWNLOAD",
    ] {
        println!("cargo:rerun-if-env-changed={var}");
    }
}

/// Resolve the compiler, or exit with instructions naming every option.
fn resolve_brievc() -> PathBuf {
    if let Some(explicit) = env_path("COUNSEL_BRIEVC").or_else(|| env_path("BRIEVC")) {
        return explicit;
    }

    if let Some(cached) = cached_binary() {
        return cached;
    }

    if let Some(on_path) = which("brievc") {
        return on_path;
    }

    if env::var_os("COUNSEL_NO_DOWNLOAD").is_some() {
        missing_compiler("COUNSEL_NO_DOWNLOAD is set, so no download was attempted");
    }

    download_toolchain();

    cached_binary().unwrap_or_else(|| {
        missing_compiler("the download completed but no binary landed in the cache")
    })
}

/// Read an env var as a path, validating that it actually exists.
fn env_path(var: &str) -> Option<PathBuf> {
    let raw = env::var_os(var)?;
    let path = PathBuf::from(raw);
    if path.is_file() {
        return Some(path);
    }
    panic!(
        "{var} points at `{}`, which does not exist.\n\
         Point it at a `brievc` binary, or unset it to let counsel resolve one.",
        path.display()
    );
}

/// The cache directory: `COUNSEL_CACHE_DIR`, else the XDG cache, else `~/.cache`.
fn cache_root() -> PathBuf {
    if let Some(dir) = env::var_os("COUNSEL_CACHE_DIR") {
        return PathBuf::from(dir);
    }
    let base = env::var_os("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .or_else(|| env::var_os("HOME").map(|home| PathBuf::from(home).join(".cache")))
        .unwrap_or_else(|| env::temp_dir());
    base.join("counsel")
}

/// Directory of the pinned, extracted toolchain inside the cache.
fn install_dir() -> PathBuf {
    cache_root().join(format!("brievc-{RELEASE_TAG}-{ASSET_STEM}"))
}

/// The cached compiler, when the pinned toolchain is already extracted.
fn cached_binary() -> Option<PathBuf> {
    let binary = install_dir().join("bin").join("brievc");
    binary.is_file().then_some(binary)
}

/// Find an executable on PATH (minimal `which`, no shell).
fn which(name: &str) -> Option<PathBuf> {
    let paths = env::var_os("PATH")?;
    env::split_paths(&paths)
        .map(|dir| dir.join(name))
        .find(|candidate| candidate.is_file())
}

/// Download, verify and extract the pinned toolchain into the cache.
fn download_toolchain() {
    if !asset_supported() {
        missing_compiler(
            "no prebuilt compiler is published for this platform \
             (only linux x86_64)",
        );
    }

    let install = install_dir();
    let cache = cache_root();
    fs::create_dir_all(&cache).unwrap_or_else(|error| {
        panic!(
            "cannot create the counsel cache at `{}`: {error}",
            cache.display()
        )
    });

    let tarball = cache.join(format!("{ASSET_STEM}-{RELEASE_TAG}.tar.gz"));
    let url = format!(
        "https://github.com/Randozart/counsel/releases/download/{RELEASE_TAG}/{ASSET_STEM}.tar.gz"
    );
    fetch(&url, &tarball);
    verify_sha256(&tarball);
    extract(&tarball, &install);
}

/// Whether a prebuilt asset exists for the target being built.
fn asset_supported() -> bool {
    env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux")
        && env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64")
}

/// Fetch `url` to `dest`, preferring curl and falling back to wget.
fn fetch(url: &str, dest: &Path) {
    let attempts: [(&str, Vec<&str>); 2] = [
        ("curl", vec!["-fL", "--retry", "3", "-o"]),
        ("wget", vec!["-q", "-O"]),
    ];
    for (tool, flags) in attempts {
        if which(tool).is_none() {
            continue;
        }
        let status = Command::new(tool)
            .args(&flags)
            .arg(dest)
            .arg(url)
            .status()
            .unwrap_or_else(|error| panic!("cannot run {tool}: {error}"));
        if status.success() {
            return;
        }
    }
    missing_compiler("neither curl nor wget could download the compiler");
}

/// Abort unless the tarball matches the pinned checksum.
fn verify_sha256(tarball: &Path) {
    let actual = sha256_of(tarball);
    assert_eq!(
        actual,
        ASSET_SHA256,
        "brievc tarball checksum mismatch — refusing to use it.\n\
         expected {ASSET_SHA256}\n  actual {actual}\n  file   {}\n\
         Delete the cache directory and retry, or set BRIEVC to a compiler you trust.",
        tarball.display()
    );
}

/// sha256 of a file, via `sha256sum` (or `shasum -a 256` on BSD/macOS).
fn sha256_of(file: &Path) -> String {
    for (tool, flags) in [("sha256sum", vec![]), ("shasum", vec!["-a", "256"])] {
        if which(tool).is_none() {
            continue;
        }
        let output = Command::new(tool)
            .args(&flags)
            .arg(file)
            .output()
            .unwrap_or_else(|error| panic!("cannot run {tool}: {error}"));
        if output.status.success() {
            let stdout = String::from_utf8_lossy(&output.stdout);
            if let Some(digest) = stdout.split_whitespace().next() {
                return digest.to_ascii_lowercase();
            }
        }
    }
    panic!(
        "cannot verify the downloaded compiler: neither `sha256sum` nor `shasum` is available.\n\
         Install one, or set BRIEVC to a compiler you have verified yourself."
    );
}

/// Extract the tarball into `install`, keeping the `<stem>/bin/share` layout.
fn extract(tarball: &Path, install: &Path) {
    let staging = cache_root().join(format!(".staging-{}", std::process::id()));
    let _ = fs::remove_dir_all(&staging);
    fs::create_dir_all(&staging)
        .unwrap_or_else(|error| panic!("cannot create `{}`: {error}", staging.display()));

    let status = Command::new("tar")
        .arg("-xzf")
        .arg(tarball)
        .arg("-C")
        .arg(&staging)
        .status()
        .unwrap_or_else(|error| panic!("cannot run tar: {error}"));
    assert!(
        status.success(),
        "cannot extract `{}` — is `tar` available?",
        tarball.display()
    );

    // Replace any previous install with the freshly extracted tree.
    let _ = fs::remove_dir_all(install);
    fs::rename(staging.join(ASSET_STEM), install)
        .unwrap_or_else(|error| panic!("cannot move the compiler into place: {error}"));
    let _ = fs::remove_dir_all(&staging);
}

/// Compile the bridge into a static library with the resolved compiler.
fn build_machinery(brievc: &Path, bridge: &Path, lib_out: &Path) {
    let output = Command::new(brievc)
        .arg("build")
        .arg(bridge)
        .arg("--library")
        .arg("--out")
        .arg(lib_out)
        .output()
        .unwrap_or_else(|error| {
            panic!(
                "cannot run `{}` ({error}).\nSet BRIEVC to a working brievc binary.",
                brievc.display()
            )
        });
    assert!(
        output.status.success(),
        "brievc build --library failed ({}):\n{}",
        brievc.display(),
        String::from_utf8_lossy(&output.stderr)
    );
}

/// Exit with one message listing every way to supply a compiler.
fn missing_compiler(reason: &str) -> ! {
    let url = format!(
        "https://github.com/Randozart/counsel/releases/download/{RELEASE_TAG}/{ASSET_STEM}.tar.gz"
    );
    let cache = install_dir();
    panic!(
        "counsel needs the Briev compiler (`brievc`) to build its predicate core.\n\
         {reason}.\n\
         \n\
         Fix it in any of these ways:\n\
         1. set BRIEVC=/path/to/brievc  (quickest)\n\
         2. install it on PATH:\n     curl -L -o brievc.tar.gz {url}\n     tar -xzf brievc.tar.gz && export PATH=$PWD/{ASSET_STEM}/bin:$PATH\n\
         3. let counsel download it: unset COUNSEL_NO_DOWNLOAD and rebuild\n     (cached under {})\n\
         4. build from source: cargo build --release --bin brievc in Randozart/briev-lang\n\
         \n\
         Other platforms have no prebuilt artifact; use option 1 or 4.",
        cache.display()
    );
}
